#include<iostream>
#include<cmath>
using namespace std;
int main(){
    double n;
    cout<<"Enter a number :";
    cin>>n;
     cout<<"Square root = "<<sqrt(n)<<endl;
     cout<<"Absolute value = "<<fabs(n)<<endl;
     cout<<"Logarithm = "<<log(n)<<endl;
     cout<<"Exponential =  "<<exp(n)<<endl;



    return 0;
}